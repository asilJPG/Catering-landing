export function formatPrice(value: number): string {
  return value.toLocaleString('ru-RU');
}

export function guestsWord(n: number): string {
  const d = n % 10;
  const h = n % 100;
  if (d === 1 && h !== 11) return 'гость';
  if (d >= 2 && d <= 4 && !(h >= 12 && h <= 14)) return 'гостя';
  return 'гостей';
}

